一个好类比要经得起「哪里不一样」的追问。火星与地球都有大气、有水、有昼夜，于是有人推「火星有生命」。反相似点立刻出现：大气稀薄、无磁场保护、表面辐射强、液态水难以长期存在。这些差异恰好打击结论，类比随之走弱。

判断反相似点的分量，只看一件事：它是否落在结论所依赖的那条机制上。落在机制上，类比重伤；落在无关处（比如两颗行星的名字都好听），可以忽略。

